import React, { useState } from 'react';
import { X, Download, Copy, Check, FileDown } from 'lucide-react';
import { StudyItem, DocInfo } from '../types';
import { sounds } from '../utils/soundEffects';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  activeDoc: DocInfo | null;
  items: StudyItem[];
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  activeDoc,
  items,
}) => {
  const [copied, setCopied] = useState(false);
  const [exportFormat, setExportFormat] = useState<'markdown' | 'json' | 'anki'>('markdown');

  if (!isOpen) return null;

  const generateMarkdown = () => {
    let md = `# ${activeDoc?.title || 'Grimoire Study Deck'}\n\n`;
    md += `*Generated by Grimoire AI — Kiroween 2026*\n\n`;
    items.forEach((item, idx) => {
      md += `### ${idx + 1}. [${item.topic}] ${item.question}\n\n`;
      md += `**Answer:** ${item.answer}\n\n`;
      md += `> **Explanation:** ${item.explanation}\n\n`;
      md += `---\n\n`;
    });
    return md;
  };

  const generateJson = () => {
    return JSON.stringify(
      {
        title: activeDoc?.title || 'Grimoire Deck',
        exportedAt: new Date().toISOString(),
        items,
      },
      null,
      2
    );
  };

  const generateAnki = () => {
    // Front<TAB>Back format
    return items
      .map((item) => `"[${item.topic}] ${item.question}"\t"${item.answer}<br><br><i>${item.explanation}</i>"`)
      .join('\n');
  };

  const getContent = () => {
    if (exportFormat === 'json') return generateJson();
    if (exportFormat === 'anki') return generateAnki();
    return generateMarkdown();
  };

  const handleCopy = () => {
    sounds.playClick();
    navigator.clipboard.writeText(getContent());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    sounds.playClick();
    const content = getContent();
    const ext = exportFormat === 'json' ? 'json' : exportFormat === 'anki' ? 'txt' : 'md';
    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${(activeDoc?.title || 'grimoire-study').toLowerCase().replace(/\s+/g, '-')}.${ext}`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-fadeIn">
      <div 
        onClick={(e) => e.stopPropagation()}
        className="haunted-glass-card rounded-2xl max-w-2xl w-full border border-arcane-500/50 p-6 shadow-glow-purple-lg relative"
      >
        <div className="flex items-center justify-between pb-4 border-b border-arcane-900 mb-5">
          <div className="flex items-center gap-2">
            <Download className="w-5 h-5 text-flame-400" />
            <h3 className="font-cinzel text-lg font-bold text-ghost-100">
              Export Arcane Study Deck
            </h3>
          </div>
          <button
            onClick={() => { sounds.playClick(); onClose(); }}
            className="p-1 rounded-lg hover:bg-sanctum-800 text-ghost-400 hover:text-ghost-100 transition-colors"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Format Selector */}
        <div className="flex items-center gap-2 mb-4">
          <button
            onClick={() => setExportFormat('markdown')}
            className={`px-3 py-1.5 rounded-lg text-xs font-medium transition-colors ${
              exportFormat === 'markdown'
                ? 'bg-arcane-600 text-white'
                : 'bg-sanctum-900 text-ghost-400 hover:text-white'
            }`}
          >
            Markdown (.md)
          </button>
          <button
            onClick={() => setExportFormat('json')}
            className={`px-3 py-1.5 rounded-lg text-xs font-medium transition-colors ${
              exportFormat === 'json'
                ? 'bg-arcane-600 text-white'
                : 'bg-sanctum-900 text-ghost-400 hover:text-white'
            }`}
          >
            JSON Format
          </button>
          <button
            onClick={() => setExportFormat('anki')}
            className={`px-3 py-1.5 rounded-lg text-xs font-medium transition-colors ${
              exportFormat === 'anki'
                ? 'bg-arcane-600 text-white'
                : 'bg-sanctum-900 text-ghost-400 hover:text-white'
            }`}
          >
            Anki Flashcards (.txt)
          </button>
        </div>

        {/* Preview Area */}
        <div className="relative mb-5">
          <textarea
            readOnly
            rows={10}
            value={getContent()}
            className="w-full p-4 rounded-xl bg-sanctum-950 border border-arcane-900 font-mono text-xs text-ghost-300 resize-none focus:outline-none"
          />
        </div>

        {/* Action Buttons */}
        <div className="flex items-center justify-between pt-3 border-t border-arcane-900">
          <span className="text-xs font-mono text-ghost-400">
            {items.length} runes prepared for export
          </span>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-4 py-2 rounded-xl bg-sanctum-900 border border-arcane-800 hover:border-arcane-600 text-ghost-200 text-xs font-semibold transition-all"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-spectral-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied!' : 'Copy to Clipboard'}</span>
            </button>

            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 px-4 py-2 rounded-xl bg-gradient-to-r from-arcane-600 to-flame-600 text-white text-xs font-semibold shadow-glow-purple hover:shadow-glow-orange transition-all"
            >
              <FileDown className="w-3.5 h-3.5" />
              <span>Download File</span>
            </button>
          </div>
        </div>

      </div>
    </div>
  );
};
